/// Service for exporting notes to PDF and other formats.
class ExportService {
  /// Exports a single note to PDF.
  static Future<Uint8List> exportNoteToPdf(Note note, {
    bool includeDrawing = true,
    bool includeMetadata = true,
    PdfPageFormat pageFormat = PdfPageFormat.a4,
  }) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: pageFormat,
        margin: const pw.EdgeInsets.all(24),
        build: (context) => [
          // Header
          if (note.title.isNotEmpty)
            pw.Header(
              level: 0,
              child: pw.Text(
                note.title,
                style: pw.TextStyle(
                  fontSize: 24,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.grey900,
                ),
              ),
            ),

          // Metadata
          if (includeMetadata) ...[
            pw.SizedBox(height: 16),
            pw.Row(
              children: [
                pw.Expanded(
                  child: pw.Text(
                    'Created: ${_formatDate(note.createdAt)}',
                    style: pw.TextStyle(
                      fontSize: 10,
                      color: PdfColors.grey600,
                    ),
                  ),
                ),
                pw.Expanded(
                  child: pw.Text(
                    'Updated: ${_formatDate(note.updatedAt)}',
                    style: pw.TextStyle(
                      fontSize: 10,
                      color: PdfColors.grey600,
                    ),
                    textAlign: pw.TextAlign.right,
                  ),
                ),
              ],
            ),
            if (note.templateId != null && note.templateId!.isNotEmpty)
              pw.Padding(
                padding: const pw.EdgeInsets.only(top: 4),
                child: pw.Text(
                  'Template: ${note.templateId}',
                  style: pw.TextStyle(
                    fontSize: 10,
                    color: PdfColors.grey600,
                    fontStyle: pw.FontStyle.italic,
                  ),
                ),
              ),
            if (note.fontFamily != null && note.fontFamily!.isNotEmpty)
              pw.Padding(
                padding: const pw.EdgeInsets.only(top: 4),
                child: pw.Text(
                  'Font: ${note.fontFamily}',
                  style: pw.TextStyle(
                    fontSize: 10,
                    color: PdfColors.grey600,
                    fontStyle: pw.FontStyle.italic,
                  ),
                ),
              ),
          ],

          pw.SizedBox(height: 24),

          // Body content
          if (note.body.isNotEmpty)
            pw.Text(
              note.body,
              style: pw.TextStyle(
                fontSize: 12,
                lineSpacing: 1.5,
              ),
            ),

          // Drawing strokes
          if (includeDrawing && note.strokes.isNotEmpty) ...[
            pw.SizedBox(height: 24),
            pw.Text(
              'Drawing',
              style: pw.TextStyle(
                fontSize: 16,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.grey800,
              ),
            ),
            pw.SizedBox(height: 12),
            ..._buildDrawingWidgets(note.strokes),
          ],

          // Footer
          pw.SizedBox(height: 32),
          pw.Divider(),
          pw.Text(
            'Generated by mylife',
            style: pw.TextStyle(
              fontSize: 8,
              color: PdfColors.grey500,
            ),
          ),
        ],
      ),
    );

    return pdf.save();
  }

  /// Exports multiple notes to a single PDF.
  static Future<Uint8List> exportNotesToPdf(List<Note> notes, {
    bool includeDrawing = true,
    String? title,
    PdfPageFormat pageFormat = PdfPageFormat.a4,
  }) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: pageFormat,
        margin: const pw.EdgeInsets.all(24),
        build: (context) => [
          // Title page
          pw.Center(
            child: pw.Column(
              mainAxisAlignment: pw.MainAxisAlignment.center,
              children: [
                pw.Text(
                  title ?? 'Notes Export',
                  style: pw.TextStyle(
                    fontSize: 32,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.grey900,
                  ),
                ),
                pw.SizedBox(height: 16),
                pw.Text(
                  '${notes.length} notes • ${DateTime.now().day}/${DateTime.now().month}/${DateTime.now().year}',
                  style: pw.TextStyle(
                    fontSize: 14,
                    color: PdfColors.grey600,
                  ),
                ),
              ],
            ),
          ),
          ...notes.map((note) => [
            pw.SizedBox(height: 24),
            pw.Divider(),
            pw.SizedBox(height: 12),
            pw.Text(
              note.title,
              style: pw.TextStyle(
                fontSize: 18,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.grey900,
              ),
            ),
            pw.SizedBox(height: 8),
            if (note.body.isNotEmpty)
              pw.Text(
                note.body,
                style: pw.TextStyle(fontSize: 11, lineSpacing: 1.4),
              ),
            if (note.strokes.isNotEmpty) ...[
              pw.SizedBox(height: 12),
              pw.Text(
                'Drawing (${note.strokes.length} strokes)',
                style: pw.TextStyle(
                  fontSize: 10,
                  color: PdfColors.grey500,
                  fontStyle: pw.FontStyle.italic,
                ),
              ),
            ],
            pw.SizedBox(height: 8),
          ]),
        ],
      ),
    );

    return pdf.save();
  }

  /// Saves PDF to device and optionally shares it.
  static Future<File?> saveAndSharePdf(
    Uint8List pdfBytes,
    String fileName, {
    bool share = true,
  }) async {
    final directory = await getApplicationDocumentsDirectory();
    final file = File('${directory.path}/$fileName');
    await file.writeAsBytes(pdfBytes);

    if (share) {
      await Share.shareXFiles(
        [XFile(file.path)],
        text: 'Exported from mylife',
      );
    }

    return file;
  }

  /// Prints the PDF directly.
  static Future<void> printPdf(Uint8List pdfBytes) async {
    await Printing.layoutPdf(
      onLayout: (format) async => pdfBytes,
    );
  }

  /// Exports a template to PDF.
  static Future<Uint8List> exportTemplateToPdf(Template template) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(24),
        build: (context) => [
          pw.Header(
            level: 0,
            child: pw.Text(
              template.name,
              style: pw.TextStyle(
                fontSize: 24,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.grey900,
              ),
            ),
          ),
          pw.SizedBox(height: 16),
          pw.Row(
            children: [
              pw.Expanded(
                child: pw.Text(
                  'Category: ${TemplateCategory.getDisplayName(template.category)}',
                  style: pw.TextStyle(fontSize: 10, color: PdfColors.grey600),
                ),
              ),
              pw.Expanded(
                child: pw.Text(
                  template.isCustom ? 'Custom Template' : 'Built-in Template',
                  style: pw.TextStyle(
                    fontSize: 10,
                    color: PdfColors.grey600,
                    fontStyle: pw.FontStyle.italic,
                  ),
                  textAlign: pw.TextAlign.right,
                ),
              ),
            ],
          ),
          pw.SizedBox(height: 24),
          pw.Text(
            template.contentJson,
            style: pw.TextStyle(fontSize: 12, lineSpacing: 1.5),
          ),
        ],
      ),
    );

    return pdf.save();
  }

  static List<pw.Widget> _buildDrawingWidgets(List<DrawingStroke> strokes) {
    if (strokes.isEmpty) return [];
    
    // Calculate bounds for all strokes to determine scaling
    double minX = double.infinity, minY = double.infinity;
    double maxX = -double.infinity, maxY = -double.infinity;
    
    for (final stroke in strokes) {
      for (final point in stroke.points) {
        minX = min(minX, point.dx);
        minY = min(minY, point.dy);
        maxX = max(maxX, point.dx);
        maxY = max(maxY, point.dy);
      }
    }
    
    // Add some padding
    const padding = 20.0;
    minX -= padding;
    minY -= padding;
    maxX += padding;
    maxY += padding;
    
    final strokeWidth = maxX - minX;
    final strokeHeight = maxY - minY;
    
    // Calculate scale to fit in PDF page (max 400x300 points)
    const maxWidth = 400.0;
    const maxHeight = 300.0;
    final scaleX = maxWidth / strokeWidth;
    final scaleY = maxHeight / strokeHeight;
    final scale = min(scaleX, scaleY);
    
    final scaledWidth = strokeWidth * scale;
    final scaledHeight = strokeHeight * scale;
    
    return [
      pw.Container(
        width: scaledWidth + 40,
        height: scaledHeight + 40,
        decoration: pw.BoxDecoration(
          border: pw.Border.all(color: PdfColors.grey300),
          borderRadius: pw.BorderRadius.circular(8),
        ),
        child: pw.Center(
          child: pw.Transform.translate(
            offset: pw.Offset(-minX * scale + 20, -minY * scale + 20),
            child: pw.CustomPaint(
              size: pw.Size(strokeWidth * scale, strokeHeight * scale),
              painter: _DrawingPdfPainter(strokes: strokes, scale: scale, offset: pw.Offset(-minX, -minY)),
            ),
          ),
        ),
      ),
    ];
  }

  static String _formatDate(DateTime date) {
    return '${date.day}/${date.month}/${date.year} ${date.hour.toString().padLeft(2, '0')}:${date.minute.toString().padLeft(2, '0')}';
  }
}

/// Custom painter for rendering drawing strokes to PDF.
class _DrawingPdfPainter extends pw.CustomPainter {
  _DrawingPdfPainter({
    required this.strokes,
    required this.scale,
    required this.offset,
  });

  final List<DrawingStroke> strokes;
  final double scale;
  final pw.Offset offset;

  @override
  void paint(pw.Canvas canvas, pw.Size size) {
    for (final stroke in strokes) {
      if (stroke.points.length < 2) continue;
      
      final pdfColor = _colorToPdfColor(stroke.color);
      final paint = pw.Paint()
        ..color = pdfColor
        ..strokeWidth = stroke.width * scale
        ..strokeCap = pw.StrokeCap.round
        ..strokeJoin = pw.StrokeJoin.round
        ..style = pw.PaintingStyle.stroke;
      
      if (stroke.color == Colors.transparent) {
        // Eraser mode - not applicable in PDF, skip
        continue;
      }
      
      final path = pw.Path();
      path.moveTo(
        (stroke.points[0].dx + offset.dx) * scale,
        (stroke.points[0].dy + offset.dy) * scale,
      );
      
      for (int i = 1; i < stroke.points.length; i++) {
        final point = stroke.points[i];
        final prevPoint = stroke.points[i - 1];
        // Smooth the path using quadratic bezier
        final midPoint = pw.Offset(
          (prevPoint.dx + point.dx) / 2 * scale + offset.dx,
          (prevPoint.dy + point.dy) / 2 * scale + offset.dy,
        );
        path.quadraticBezierTo(
          (prevPoint.dx * scale) + offset.dx,
          (prevPoint.dy * scale) + offset.dy,
          midPoint.dx,
          midPoint.dy,
        );
      }
      
      canvas.drawPath(path, paint);
    }
  }
  
  @override
  bool shouldRepaint(covariant _DrawingPdfPainter oldDelegate) {
    return oldDelegate.strokes != strokes ||
        oldDelegate.scale != scale ||
        oldDelegate.offset != offset;
  }
  
  pw.PdfColor _colorToPdfColor(Color color) {
    return pw.PdfColor.fromInt(color.value);
  }
}

/// Extension for printing/share functionality.
extension ExportServiceExt on ExportService {
  /// Quick export and share a note.
  static Future<void> quickShareNote(Note note) async {
    final pdfBytes = await exportNoteToPdf(note);
    final fileName = '${note.title.replaceAll(RegExp(r'[^\w]'), '_')}_${DateTime.now().millisecondsSinceEpoch}.pdf';
    await saveAndSharePdf(pdfBytes, fileName);
  }
}